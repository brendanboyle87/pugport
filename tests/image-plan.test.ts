import assert from 'node:assert/strict';
import { test } from 'node:test';
import {
  imagePlanPrompt,
  parseImagePlan,
  understandImageRequest,
  type ImagePlanInput,
} from '../src/server/image-plan.ts';

const input: ImagePlanInput = {
  request: '我说的是这个人物，刚才的图片只是给你作为服饰参考，生成几个不同姿势',
  conversation: [
    { role: 'owner', text: '刚才的人物保持不变，换上这套我给你发的服饰', pictures: ['outfit'] },
    { role: 'pugport', text: '已生成图片。', pictures: ['grid'] },
  ],
  references: [
    { attachmentId: 'person', label: 'attached by the owner to this message (person.png)' },
    { attachmentId: 'grid', label: 'generated by PugPort in the latest reply' },
    { attachmentId: 'outfit', label: 'attached by the owner to an earlier message' },
  ],
  documentPrompts: [{ title: '林照', language: 'zh', prompt: '全身立姿人像摄影，林照，站姿挺拔。' }],
};

test('the planner sees the words, the turns, every picture with its origin, and the document prompts', () => {
  const prompt = imagePlanPrompt(input);
  assert.match(prompt, /Owner message:\n我说的是这个人物/);
  assert.match(prompt, /Owner: 刚才的人物保持不变.*\[pictures: R3\]/);
  assert.match(prompt, /R2: generated by PugPort in the latest reply/);
  assert.match(prompt, /D1 \[林照, zh\]: 全身立姿/);
  assert.match(prompt, /a child wears ordinary children's clothes/);
});

test('each planned picture keeps its own references, a document base, and drops unknown keys', () => {
  const items = parseImagePlan(
    '```json\n' +
      JSON.stringify({
        images: [
          {
            title: '人物 1',
            prompt: 'the face and body of reference 1, the outfit of reference 2, standing',
            references: ['R1', 'R3'],
          },
          { title: '人物 2', prompt: 'same, walking', references: ['R1', 'R3', 'R9', 'R1'] },
          { base: 'D1', prompt: '本张造型：风衣。', references: [] },
          { base: 'D7', prompt: '' },
          'a plain prompt',
        ],
      }) +
      '\n```',
    input,
  )!;
  assert.deepEqual(items[0], {
    title: '人物 1',
    prompt: 'the face and body of reference 1, the outfit of reference 2, standing',
    references: ['person', 'outfit'],
  });
  assert.deepEqual(items[1]!.references, ['person', 'outfit']);
  assert.deepEqual(items[2], {
    title: '林照',
    prompt: '全身立姿人像摄影，林照，站姿挺拔。\n\n本张造型：风衣。',
    references: [],
  });
  assert.deepEqual(items[3], { prompt: 'a plain prompt' });
  assert.equal(items.length, 4);
});

test('a failed, slow or empty planner leaves the decision to the caller', async () => {
  assert.equal(await understandImageRequest(input, async () => 'no json here'), undefined);
  assert.equal(await understandImageRequest(input, async () => '{"images":[]}'), undefined);
  assert.equal(
    await understandImageRequest(input, async () => {
      throw new Error('down');
    }),
    undefined,
  );
  assert.equal(await understandImageRequest(input, () => new Promise(() => undefined), { timeoutMs: 20 }), undefined);
});
